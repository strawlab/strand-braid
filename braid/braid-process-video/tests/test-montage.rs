/// The names in `dir`, sorted.
fn names_in(dir: &std::path::Path) -> Vec<String> {
    let mut names: Vec<String> = std::fs::read_dir(dir)
        .unwrap()
        .map(|entry| entry.unwrap().file_name().into_string().unwrap())
        .collect();
    names.sort();
    names
}

/// When processing fails, no .braidz file may be written, because one cut
/// short would look complete, and the directory it was being assembled in is
/// deleted.
#[ignore]
#[tokio::test]
async fn test_failed_run_writes_no_braidz() -> anyhow::Result<()> {
    init_logging();
    let outdir = tempfile::tempdir()?;
    let path_str = |name: &str| outdir.path().join(name).to_str().unwrap().to_string();

    // A regular file where the video output wants its directory. Setting that
    // output up fails, after the braidz output before it has been started.
    std::fs::write(outdir.path().join("blocker"), "")?;
    let output = vec![
        OutputConfig::Braidz(BraidzOutputConfig {
            filename: path_str("out.braidz"),
        }),
        OutputConfig::Video(VideoOutputConfig {
            filename: path_str("blocker/out.mp4"),
            video_options: Default::default(),
        }),
    ];
    let cfg = get_files_with_output("fc6-led-4fps-5-cams-dark", Some(10), output)?;
    assert!(braid_process_video::run_config(&cfg, false).await.is_err());

    // The braidz writer disposes of its directory in the background, and may
    // not even have created it yet. Wait until only the blocker has been there
    // for a full second.
    let mut clean_polls = 0;
    for _ in 0..400 {
        clean_polls = if names_in(outdir.path()) == ["blocker"] {
            clean_polls + 1
        } else {
            0
        };
        if clean_polls == 20 {
            break;
        }
        tokio::time::sleep(std::time::Duration::from_millis(50)).await;
    }
    assert_eq!(names_in(outdir.path()), ["blocker"]);
    Ok(())
}

/// The `.braid` directory is deleted when processing fails, so processing must
/// refuse to start in one which already exists, and must leave it alone.
#[ignore]
#[tokio::test]
async fn test_refuses_an_existing_braid_dir() -> anyhow::Result<()> {
    init_logging();
    let outdir = tempfile::tempdir()?;
    let existing = outdir.path().join("out.braid");
    std::fs::create_dir(&existing)?;
    std::fs::write(existing.join("precious.txt"), "not ours to delete")?;

    let output = vec![OutputConfig::Braidz(BraidzOutputConfig {
        filename: outdir
            .path()
            .join("out.braidz")
            .to_str()
            .unwrap()
            .to_string(),
    })];
    let cfg = get_files_with_output("fc6-led-4fps-5-cams-dark", Some(10), output)?;
    assert!(braid_process_video::run_config(&cfg, false).await.is_err());

    tokio::time::sleep(std::time::Duration::from_secs(1)).await;
    assert_eq!(names_in(outdir.path()), ["out.braid"]);
    assert_eq!(
        std::fs::read_to_string(existing.join("precious.txt"))?,
        "not ours to delete"
    );
    Ok(())
}
