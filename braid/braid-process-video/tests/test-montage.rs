const BASE_URL: &str = "https://strawlab-cdn.com/assets/flycube6-videos";
const SOURCE_JSON: &str = include_str!("source.json");

async fn do_config(cfg: &Valid<BraidRetrackVideoConfig>) -> anyhow::Result<()> {
    // The outputs have fixed names. Remove what an earlier run left, so that
    // the checks below cannot pass on a stale file.
    for output in cfg.valid().output.iter() {
        match std::fs::remove_file(output.filename()) {
            Ok(()) => {}
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
            Err(e) => return Err(e.into()),
        }
    }

    // Generate the output using the config generated by the `get_files` function.
    let output_fnames = braid_process_video::run_config(cfg, false).await?;

    // Check the output for this config. Note this requires knowledge of what
    // `get_files` specified.
    assert_eq!(output_fnames.len(), 2);
    let output_mp4 = output_fnames[0].clone();

    // Each output is written under a temporary name beside it, which must be
    // gone once the output is in place.
    for output_fname in output_fnames.iter() {
        assert!(output_fname.exists(), "{}", output_fname.display());
        let partial_files: Vec<_> = std::fs::read_dir(output_fname.parent().unwrap())?
            .map(|entry| entry.unwrap().file_name().into_string().unwrap())
            .filter(|name| name.ends_with(".partial"))
            .collect();
        assert!(partial_files.is_empty(), "{partial_files:?}");
    }

    // start parsing video output
    let _src = frame_source::FrameSourceBuilder::new(&output_mp4)
        .do_decode_h264(false)
        .build_source()?;

    // TODO: check output video further.

    // check output braidz
    let output_braidz = &output_fnames[1];
    assert_eq!("braidz", output_braidz.extension().unwrap());
    // The directory it was assembled in is gone.
    assert!(!output_braidz.with_extension("braid").exists());
    let _out_ar = braidz_parser::braidz_parse_path(output_braidz)?;

    if let Some(input_braidz) = &cfg.valid().input_braidz {
        let _in_ar = braidz_parser::braidz_parse_path(input_braidz)?;
        // TODO: compare results reasonably.
    }

    Ok(())
}

fn parse_file_list(dirname: &str) -> anyhow::Result<Vec<(String, String)>> {
    let source_json: serde_json::Value = serde_json::from_str(SOURCE_JSON)?;
    let source_json = source_json.as_object().unwrap();
    let files = source_json.get(dirname).unwrap().as_array().unwrap();
    let mut results = vec![];
    for file_src in files {
        let elements = file_src.as_array().unwrap();
        assert_eq!(elements.len(), 2);
        let fname = elements[0].as_str().unwrap();
        let sha256sum = elements[1].as_str().unwrap();
        results.push((fname.to_string(), sha256sum.to_string()));
    }
    Ok(results)
}

fn get_files(
    dirname: &str,
    max_num_frames: Option<usize>,
) -> anyhow::Result<Valid<BraidRetrackVideoConfig>> {
    let output = vec![
        OutputConfig::Video(VideoOutputConfig {
            filename: format!("scratch/rendered/{}.mp4", dirname),
            video_options: Default::default(),
        }),
        OutputConfig::Braidz(BraidzOutputConfig {
            filename: format!("scratch/rendered/{dirname}.braidz"),
        }),
    ];
    get_files_with_output(dirname, max_num_frames, output)
}

/// As [`get_files`], but writing to the given outputs.
fn get_files_with_output(
    dirname: &str,
    max_num_frames: Option<usize>,
    output: Vec<OutputConfig>,
) -> anyhow::Result<Valid<BraidRetrackVideoConfig>> {
    let file_list = parse_file_list(dirname)?;

    let outdir = format!("scratch/downloaded-data/{}", dirname);
    let mut input_braidz = None;
    let mut input_video = vec![];
    for (fname, sha256sum) in file_list.iter() {
        let dest = format!("{}/{}", outdir, fname);
        download_verify::download_verify(
            format!("{}/{}/{}", BASE_URL, dirname, fname).as_str(),
            &dest,
            &download_verify::Hash::Sha256(sha256sum.into()),
        )?;

        if fname.ends_with(".braidz") {
            input_braidz = Some(dest);
        } else {
            // Get everything before first '.'.
            let stem = fname.split('.').next().unwrap();

            // Convert "movie20211109_080701_Basler-21714402" to "Basler-21714402".
            let camera_name = stem.split('_').skip(2).collect::<Vec<_>>().join("_");

            input_video.push(VideoSourceConfig {
                filename: dest,
                camera_name: Some(camera_name),
                ..Default::default()
            });
        }
    }

    let cfg = BraidRetrackVideoConfig {
        input_braidz,
        input_video,
        output,
        max_num_frames,
        ..Default::default()
    };

    let basedir: Option<String> = None;
    cfg.validate(basedir)
}

